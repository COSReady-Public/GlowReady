const STRINGS = { en: EN, 'zh-CN': ZH_CN, 'zh-TW': ZH_TW };

const valid = l => (LOCALES.includes(l) ? l : 'en');

// locale.js has already chosen the language and put it on <html data-locale>.
let locale = typeof document !== 'undefined' ? valid(document.documentElement.getAttribute('data-locale')) : 'en';

export const getLocale = () => locale;
export function setLocale(l) { locale = valid(l); }

/** Text for a key in the current language; {name} placeholders filled from vars. */
export function t(key, vars) {
  const v = STRINGS[locale][key] ?? EN[key] ?? key;
  return vars ? v.replace(/\{(\w+)\}/g, (m, k) => (k in vars ? vars[k] : m)) : v;
}

/** A preset's name and labels in the current language. */
export function presetText(p) {
  const zh = locale !== 'en' && STRINGS[locale]['preset.' + p.id];
  return zh ? { name: zh[0], b: zh[1], a: zh[2] } : { name: p.name, b: p.b, a: p.a };
}

/** Swap the page's English copy for the current language (no-op in English). */
export function translatePage(root = document) {
  if (locale === 'en') return;
  root.querySelectorAll('[data-i18n]').forEach(el => { el.textContent = t(el.dataset.i18n); });
  root.querySelectorAll('[data-i18n-aria]').forEach(el => el.setAttribute('aria-label', t(el.dataset.i18nAria)));
}

